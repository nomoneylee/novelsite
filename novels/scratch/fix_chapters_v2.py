def main():
    print("開始執行古典化名詞與俗體字批量修復 (V4最終超強版)...")
    modified_files = []
    
    # 獲取所有正文檔案
    files = [f for f in os.listdir(NOVEL_DIR) if f.endswith(".md") and f != "README.md"]
    
    for filename in files:
        filepath = os.path.join(NOVEL_DIR, filename)
        with open(filepath, "r", encoding="utf-8", errors="ignore") as f:
            content = f.read()
            
        original_content = content
        
        # 1. 執行特定詞彙替換
        for old, new in phrase_replacements.items():
            if old in content:
                content = content.replace(old, new)
                
        # 2. 用正則表達式安全替換「慣性」，避開「習慣性」
        content = re.sub(r"(?<!習慣)慣性", "慣力", content)
        
        # 3. 針對第 47 章和第 48 章做一些人工精調的特殊替換
        if filename == "第47章_連勝六門氣力竭.md":
            content = content.replace("在大氣中留下了", "在半空中留下了")
            content = content.replace("大氣中留下了", "半空中留下了")
            content = content.replace("大氣中", "空氣中")
            content = content.replace("體內的氣壓會下降三成", "體內的內息會衰減三成")
            
        if filename == "第48章_斷首少室洗舊盟.md":
            content = content.replace("吸力氣旋，鎖死了", "氣旋渦流，鎖死了")
            content = content.replace("體內的氣壓會下降三成", "體內的內息會衰減三成")
            content = content.replace("大衍求一密碼", "大衍同餘密印")
            content = content.replace("主數與餘數完全吻合", "主數與餘數完全相合")

        if content != original_content:
            with open(filepath, "w", encoding="utf-8") as f:
                f.write(content)
            modified_files.append(filename)
            
    print(f"替換修復完成！共修改了 {len(modified_files)} 個章節。")
    print("修改章節列表:", modified_files)

if __name__ == "__main__":
    main()
